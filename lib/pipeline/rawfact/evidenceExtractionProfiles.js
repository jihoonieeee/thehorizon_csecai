// ── Public API ────────────────────────────────────────────────────────────────

export function getExtractionProfile(sourceType) {
  return EXTRACTION_PROFILES[sourceType] ?? EXTRACTION_PROFILES.unknown;
}

/**
 * Get the extraction profile for a source type, adjusted for concreteness.
 *
 * The concreteness_class from evidenceEligibility sets an extraction_depth_hint
 * that modifies max_items:
 *   deep     — +2 items (concrete content warrants deeper extraction)
 *   standard — no change
 *   shallow  — -1 items (vague/marketing content warrants shallower extraction)
 *
 * @param {string} sourceType
 * @param {string} [depthHint="standard"] - from evidence_eligibility.extraction_depth_hint
 * @returns {object} extraction profile with adjusted max_items
 */
export function getExtractionProfileWithDepth(sourceType, depthHint = "standard") {
  const profile = getExtractionProfile(sourceType);
  if (!profile || profile.max_items === 0) return profile;

  let maxItems = profile.max_items;
  if (depthHint === "deep")    maxItems = Math.min(maxItems + 2, 7);
  if (depthHint === "shallow") maxItems = Math.max(maxItems - 1, 1);

  return { ...profile, max_items: maxItems };
}

export function applyExtractionProfiles(sources) {
  return sources.map((source) => {
    const depthHint = source.evidence_eligibility?.extraction_depth_hint || "standard";
    return {
      ...source,
      extraction_profile: getExtractionProfileWithDepth(source.source_type || "unknown", depthHint),
    };
  });
}
