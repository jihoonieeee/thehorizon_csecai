// ── Canonical evidence types (extractor-level only) ──────────────���────────────
//
// These are the ONLY types the LLM extractor may emit. They represent concrete,
// source-grounded facts at either raw_fact or derived_observation abstraction level.
//
// INTENTIONALLY EXCLUDED from this list (synthesis layer only):
//   strategic_signal   — must be generated by L6 from multiple corroborating items
//   ecosystem_shift    — synthesis output unless source explicitly documents one
//   trust_boundary_shift — synthesis output unless source describes a concrete permission change
//
// INTENTIONALLY REMOVED (replaced by metadata fields on items):
//   timeline_event — use event_date / date_range fields on the relevant item
//   statistic      — attach as metric{} to the relevant evidence item; standalone stats are noise

export const ALL_EVIDENCE_TYPES = [
  "incident_event",          // Confirmed real-world attack, breach, or harmful deployment
  "vulnerability_fact",      // Disclosed weakness in a system, model, or protocol
  "exploit_chain",           // Specific ordered exploitation sequence tied to a concrete target
  "attack_method",           // General reusable technique or procedure (not target-specific)
  "threat_actor_activity",   // Observed behavior attributed to a named actor or campaign
  "adversary_adoption",      // Signal that real adversaries are using or testing a capability
  "capability_delta",        // Explicit comparison showing capability expansion (requires before/after)
  "research_result",         // Finding from controlled research — what the study found
  "benchmark_result",        // Measured performance value (success rate, score, etc.)
  "societal_harm",           // Real-world harm caused by AI-enabled activity
  "governance_action",       // Policy, regulation, advisory, or official guidance issued
  "defensive_control",       // Mitigation, detection rule, or protective measure
  "mitigation",              // Recommended or deployed countermeasure
  "infrastructure_dependency", // New or risky dependency in the AI supply/delivery chain
];

